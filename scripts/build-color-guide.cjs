const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=name=>JSON.parse(fs.readFileSync(path.join(root,'config/styling',name+'.json'),'utf8'));
const data={rules:read('色彩DNA/色彩类型分析/色彩类型分析-推荐规则'),plans:read('色彩DNA/色彩搭配/色彩搭配指南-配色方案'),library:read('色彩DNA/色彩搭配/色彩搭配指南-图片库')};
data.copy=read('色彩DNA/色彩类型分析/色彩类型分析-界面文案');
data.pageCopy=read('色彩DNA/色彩搭配/色彩搭配指南-界面文案');
for(const rule of [...data.rules.rules,data.rules.fallback]){
 const copy=data.copy.results[rule.contentId];
 if(!copy?.label?.trim()||!copy?.summary?.trim())throw Error('缺少结果文案 '+rule.contentId);
 Object.assign(rule,copy);
}
for(const group of [data.copy.report,data.pageCopy])for(const [key,value] of Object.entries(group))if(typeof value!=='string'||!value.trim())throw Error('界面文案为空 '+key);
const refs=read('判断依据-文献与理论');
for(const id of [...data.rules.sourceIds,...data.plans.chapters.flatMap(x=>x.sourceIds)])if(!refs.sources.some(s=>s.id===id))throw Error('未知文献 '+id);
data.sources=refs.sources.filter(s=>data.rules.sourceIds.includes(s.id));
const ids=new Set();
for(const item of data.library.images){
 if(ids.has(item.id)||!item.source||!item.rights||!item.alt||!Array.isArray(item.tags)||!item.src.startsWith('/assets/')||item.src.includes('..'))throw Error('图片记录无效 '+item.id);
 ids.add(item.id);
 if(!fs.existsSync(path.join(root,'miniprogram',item.src)))throw Error('图片不存在 '+item.src);
}
for(const rule of [...data.rules.rules,data.rules.fallback])if(!data.plans.palettes[rule.palette]||!rule.summary||!rule.reason)throw Error('配色规则无效 '+rule.id);
for(const colors of [...Object.values(data.plans.palettes).flat(),data.plans.basics])for(const c of colors)if(!/^#[0-9a-f]{6}$/i.test(c.hex)||!c.name)throw Error('色板无效');
const output='// Generated by scripts/build-color-guide.cjs. Edit config/styling instead.\nmodule.exports='+JSON.stringify(data,null,2)+';\n';
const target=path.join(root,'miniprogram/packages/analysis/utils/color-guide-data.js');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('色彩配置尚未同步，请运行 npm run build:color-guide');}
else fs.writeFileSync(target,output);
console.log('Color guide configuration validated and '+(process.argv.includes('--check')?'in sync.':'built.'));

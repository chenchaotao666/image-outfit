const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = 'config/llm-prompt/形象DNA/眼镜推荐/眼镜推荐-镜框图库.json';
const {frames} = JSON.parse(fs.readFileSync(path.join(root, source), 'utf8'));
const matches = require('../config/llm-prompt/形象DNA/眼镜推荐/眼镜推荐-推荐规则.json');
const {frameOrder} = require('../miniprogram/packages/analysis/utils/eyewear-match');
for (const [face, rule] of Object.entries(matches)) {
  const names = frameOrder(rule);
  if (rule['一般'].length !== 2 || rule['不推荐'].length !== 2 || new Set(names).size !== 5 ||
      names.some(name => typeof name !== 'string' || !Object.hasOwn(frames, name))) throw Error('脸型与镜框配置无效 ' + face);
}
const images = {};
const shapes = {};
for (const [name, file] of Object.entries(frames)) {
  const asset = '/packages/analysis/assets/eyewear/' + file;
  if (!fs.existsSync(path.join(root, 'miniprogram', asset))) throw Error('缺少镜框图片 ' + asset);
  images[name] = asset;
  shapes[name] = path.parse(file).name;
}
const out = '// Generated by scripts/build-eyewear.cjs\nmodule.exports=' + JSON.stringify({images, shapes, matches}, null, 2) + ';\n';
const target = path.join(root, 'miniprogram/packages/analysis/utils/eyewear-images.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== out) throw Error('请运行 npm run build:styling 同步镜框图库');
} else {
  fs.writeFileSync(target, out);
}
